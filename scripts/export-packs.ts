/**
 * scripts/export-packs.ts
 *
 * Dump every published industry_pack (+ its compliance profile) to
 * supabase/migrations/_packs/<slug>.sql so DB-authored packs become
 * code-managed seed migrations. Idempotent — re-running overwrites.
 *
 * Usage:
 *   npx ts-node scripts/export-packs.ts            # all published packs
 *   npx ts-node scripts/export-packs.ts vet_clinic # specific slugs
 *
 * Requires SUPABASE_URL + SUPABASE_SERVICE_ROLE_KEY in env.
 */

import * as fs from 'fs'
import * as path from 'path'
import { exportPack } from '../lib/packs/import-export'
import { supabaseAdmin } from '../lib/supabase'

const OUT_DIR = path.join(process.cwd(), 'supabase', 'migrations', '_packs')

function jsonbLiteral(obj: unknown): string {
  // Single-quote-escaped JSON for inline jsonb literal.
  return `'${JSON.stringify(obj).replace(/'/g, "''")}'::jsonb`
}

function arrayLiteral(items: string[]): string {
  if (!items.length) return "ARRAY[]::TEXT[]"
  return `ARRAY[${items.map(s => `'${s.replace(/'/g, "''")}'`).join(',')}]::TEXT[]`
}

function buildMigration(bundle: NonNullable<Awaited<ReturnType<typeof exportPack>>>): string {
  const { pack, compliance_profile: cp } = bundle
  const lines: string[] = []

  lines.push(`-- Auto-exported pack: ${pack.slug} v${pack.version}`)
  lines.push(`-- Generated by scripts/export-packs.ts — do not edit by hand.`)
  lines.push('')

  if (cp) {
    lines.push(`INSERT INTO compliance_profiles (slug, name, flags, disclosure_templates, blocked_phrases, required_disclosures) VALUES (`)
    lines.push(`  '${cp.slug}',`)
    lines.push(`  '${cp.name.replace(/'/g, "''")}',`)
    lines.push(`  ${jsonbLiteral(cp.flags)},`)
    lines.push(`  ${jsonbLiteral(cp.disclosure_templates)},`)
    lines.push(`  ${jsonbLiteral(cp.blocked_phrases)},`)
    lines.push(`  ${jsonbLiteral(cp.required_disclosures)}`)
    lines.push(`) ON CONFLICT (slug) DO UPDATE SET`)
    lines.push(`  name = EXCLUDED.name,`)
    lines.push(`  flags = EXCLUDED.flags,`)
    lines.push(`  disclosure_templates = EXCLUDED.disclosure_templates,`)
    lines.push(`  blocked_phrases = EXCLUDED.blocked_phrases,`)
    lines.push(`  required_disclosures = EXCLUDED.required_disclosures,`)
    lines.push(`  updated_at = NOW();`)
    lines.push('')
  }

  lines.push(`INSERT INTO industry_packs (`)
  lines.push(
    `  slug, name, version, tier, status, description, compliance_profile_id, kb_schema, tool_subset, required_integrations, optional_integrations, default_voice_profile`,
  )
  lines.push(`) VALUES (`)
  lines.push(`  '${pack.slug}',`)
  lines.push(`  '${pack.name.replace(/'/g, "''")}',`)
  lines.push(`  '${pack.version}',`)
  lines.push(`  ${pack.tier ? `'${pack.tier}'` : 'NULL'},`)
  lines.push(`  '${pack.status}',`)
  lines.push(`  ${pack.description ? `'${pack.description.replace(/'/g, "''")}'` : 'NULL'},`)
  lines.push(
    `  ${cp ? `(SELECT id FROM compliance_profiles WHERE slug = '${cp.slug}')` : 'NULL'},`,
  )
  lines.push(`  ${jsonbLiteral(pack.kb_schema)},`)
  lines.push(`  ${jsonbLiteral(pack.tool_subset)},`)
  lines.push(`  ${arrayLiteral(pack.required_integrations)},`)
  lines.push(`  ${arrayLiteral(pack.optional_integrations)},`)
  lines.push(`  ${jsonbLiteral(pack.default_voice_profile)}`)
  lines.push(`) ON CONFLICT (slug) DO UPDATE SET`)
  lines.push(`  name = EXCLUDED.name,`)
  lines.push(`  version = EXCLUDED.version,`)
  lines.push(`  tier = EXCLUDED.tier,`)
  lines.push(`  status = EXCLUDED.status,`)
  lines.push(`  description = EXCLUDED.description,`)
  lines.push(`  compliance_profile_id = EXCLUDED.compliance_profile_id,`)
  lines.push(`  kb_schema = EXCLUDED.kb_schema,`)
  lines.push(`  tool_subset = EXCLUDED.tool_subset,`)
  lines.push(`  required_integrations = EXCLUDED.required_integrations,`)
  lines.push(`  optional_integrations = EXCLUDED.optional_integrations,`)
  lines.push(`  default_voice_profile = EXCLUDED.default_voice_profile,`)
  lines.push(`  updated_at = NOW();`)
  lines.push('')

  return lines.join('\n')
}

async function listPublishedSlugs(): Promise<string[]> {
  const { data, error } = await supabaseAdmin
    .from('industry_packs')
    .select('slug')
    .eq('status', 'published')
    .order('slug')
  if (error) throw new Error(error.message)
  return ((data ?? []) as any[]).map(r => r.slug)
}

async function main() {
  if (!fs.existsSync(OUT_DIR)) fs.mkdirSync(OUT_DIR, { recursive: true })

  const args = process.argv.slice(2)
  const slugs = args.length > 0 ? args : await listPublishedSlugs()

  let written = 0
  for (const slug of slugs) {
    const bundle = await exportPack(slug)
    if (!bundle) {
      console.warn(`[skip] ${slug}: not found`)
      continue
    }
    const sql = buildMigration(bundle)
    const file = path.join(OUT_DIR, `${slug}.sql`)
    fs.writeFileSync(file, sql, 'utf8')
    console.log(`[ok] ${slug} → ${path.relative(process.cwd(), file)}`)
    written++
  }
  console.log(`\nWrote ${written} pack(s) to ${path.relative(process.cwd(), OUT_DIR)}`)
}

main().catch(e => {
  console.error(e)
  process.exit(1)
})
